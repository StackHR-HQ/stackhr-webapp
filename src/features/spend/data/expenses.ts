function employeeRef(id: string) {
  const employee = EMPLOYEES.find((candidate) => candidate.id === id)
  if (!employee) throw new Error(`Unknown employee id: ${id}`)
  return { employeeId: employee.id, employeeName: employee.fullName, avatarInitials: employee.avatarInitials }
}

